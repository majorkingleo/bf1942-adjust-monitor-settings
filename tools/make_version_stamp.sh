#!/bin/sh
#
# Prints the generated version stamp header on stdout. Called by make - see the version_stamp.h
# rule in Makefile.am - so the commit a binary was built from is refreshed on every build rather
# than only when configure happens to run again.
#
# Deliberately NO build timestamp. The build is reproducible: the linker is told not to write a PE
# timestamp (AM_LDFLAGS) and the deploy script zeroes the one strip adds afterwards. A "built at"
# string would quietly undo that, because two builds of the same source would produce different
# binaries again - and in the repository that consumes these programs that shows up as a binary
# diff which means nothing.
#
# A source tree without .git (a tarball, say) still produces a valid header: it says "unknown"
# rather than failing the build.

set -eu

srcdir="${1:-.}"

if commit=$( git -C "$srcdir" rev-parse --short=7 HEAD 2>/dev/null ); then
	date=$( git -C "$srcdir" log -1 --format=%cs 2>/dev/null || echo unknown )
else
	commit=unknown
	date=unknown
fi

cat <<EOF
/* Generated by tools/make_version_stamp.sh - do not edit, do not commit. */
#pragma once

/// The commit the binaries were built from, and the date of that commit.
#define TOOL_VERSION_COMMIT "$commit"
#define TOOL_VERSION_DATE   "$date"
EOF
